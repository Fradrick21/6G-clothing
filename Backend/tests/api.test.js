const { test, before, after } = require('node:test');
const assert = require('node:assert/strict');
const { connectTestDatabase } = require('./database');
process.env.JWT_SECRET = 'test-only-secret-for-isolated-integration-tests';
const app = require('../src/app');
const User = require('../src/models/User');
const { Contact, Subscriber } = require('../src/models/Submission');
let server, base, cleanup;
before(async () => {
  cleanup = await connectTestDatabase();
  server = app.listen(0, '127.0.0.1');
  await new Promise((resolve) => server.once('listening', resolve));
  base = `http://127.0.0.1:${server.address().port}/api`;
});
after(async () => {
  if (server) { server.closeAllConnections(); await new Promise((resolve) => server.close(resolve)); }
  if (cleanup) await cleanup();
});
async function call(path, method = 'GET', body, cookie) {
  const response = await fetch(base + path, { method, headers: { 'Content-Type': 'application/json', ...(cookie ? { Cookie: cookie } : {}) }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
  return { status: response.status, data: await response.json(), cookie: response.headers.get('set-cookie')?.split(';')[0] };
}
const address = { id: 'addr_test', name: 'Test Shopper', phone: '9876543210', line1: '123 Main Street', city: 'Chennai', state: 'Tamil Nadu', pincode: '600001', type: 'Home', isDefault: true };
test('real authentication, persistence, validation, isolated accounts and server priced checkout', async () => {
  assert.equal((await call('/account')).status, 401);
  assert.equal((await call('/auth/login', 'POST')).status, 400);
  assert.equal((await call('/auth/register', 'POST', { name: 'A', email: 'bad', password: 'Password1!' })).status, 400);
  const registered = await call('/auth/register', 'POST', { name: 'Test Shopper', email: ' SHOPPER@example.com ', password: 'Password1!' });
  assert.equal(registered.status, 201);
  assert.equal(registered.data.user.email, 'shopper@example.com');
  assert.equal(registered.data.user.password, undefined);
  assert.equal(registered.data.loginRequired, true);
  assert.equal(registered.cookie, 'sixg_session=');
  assert.equal((await call('/account', 'GET', undefined, registered.cookie)).status, 401);
  const savedBeforeLogin = await User.findById(registered.data.user.id);
  assert.equal(savedBeforeLogin.email, 'shopper@example.com');
  const oldRegistrationToken = require('jsonwebtoken').sign({ userId: String(savedBeforeLogin._id) }, process.env.JWT_SECRET);
  assert.equal((await call('/account', 'GET', undefined, `sixg_session=${oldRegistrationToken}`)).status, 401);
  const signedIn = await call('/auth/login', 'POST', { email: 'shopper@example.com', password: 'Password1!' });
  assert.equal(signedIn.status, 200);
  const cookie = signedIn.cookie;
  assert.ok(cookie);
  assert.equal((await call('/auth/register', 'POST', { name: 'Duplicate', email: 'shopper@example.com', password: 'Password1!' })).status, 409);
  assert.equal((await call('/auth/login', 'POST', { email: 'shopper@example.com', password: 'Wrong1!' })).status, 401);
  assert.equal((await call('/auth/login', 'POST', { email: 'SHOPPER@example.com', password: 'Password1!' })).status, 200);
  const stored = await User.findOne({ email: 'shopper@example.com' });
  assert.notEqual(stored.password, 'Password1!');
  const cart = [{ id: 'classic-logo-tee', size: 'L', color: 'Black', qty: 2, selected: true }, { id: 'wave-graphic-tee', size: 'M', color: 'Black', qty: 1, selected: false }];
  assert.equal((await call('/account/cart', 'PUT', { cart: [{ ...cart[0], qty: -1 }] }, cookie)).status, 400);
  assert.equal((await call('/account/cart', 'PUT', { cart: [{ ...cart[0], color: '<script>' }] }, cookie)).status, 400);
  assert.equal((await call('/account/cart', 'PUT', { cart }, cookie)).status, 200);
  assert.equal((await call('/account/orders', 'POST', {}, cookie)).status, 400);
  assert.equal((await call('/account/addresses', 'PUT', { addresses: [address] }, cookie)).status, 200);
  assert.equal((await call('/account/wishlist', 'PUT', { wishlist: ['manga-panel-tee'] }, cookie)).status, 200);
  assert.equal((await call('/account/profile', 'PATCH', { name: 'Updated', email: 'shopper@example.com', phone: '9876543210', role: 'admin' }, cookie)).status, 200);
  const current = await call('/account', 'GET', undefined, cookie);
  assert.equal(current.data.profile.name, 'Updated');
  assert.equal(current.data.profile.role, 'user');
  assert.deepEqual(current.data.cart, cart);
  const second = await call('/auth/register', 'POST', { name: 'Second', email: 'second@example.com', password: 'Password1!' });
  assert.equal((await call('/account', 'GET', undefined, second.cookie)).status, 401);
  const secondLogin = await call('/auth/login', 'POST', { email: second.data.user.email, password: 'Password1!' });
  const other = await call('/account', 'GET', undefined, secondLogin.cookie);
  assert.deepEqual(other.data.cart, []);
  assert.deepEqual(other.data.addresses, []);
  const attempts = await Promise.all([call('/account/orders', 'POST', { total: 1 }, cookie), call('/account/orders', 'POST', { total: 1 }, cookie)]);
  assert.equal(attempts.filter((r) => r.status === 201).length, 1);
  const placed = attempts.find((r) => r.status === 201).data;
  assert.equal(placed.order.total, 1298);
  assert.equal(placed.order.items, 2);
  assert.equal(placed.order.paymentStatus, 'Unpaid');
  assert.deepEqual(placed.cart, [cart[1]]);
  const persisted = await call('/account', 'GET', undefined, cookie);
  assert.equal(persisted.data.orders.length, 1);
  assert.equal(persisted.data.addresses[0].line1, address.line1);
  assert.equal((await call('/account/addresses', 'PUT', { addresses: [{ ...address, line1: '456 Updated Street' }] }, cookie)).status, 200);
  assert.equal((await call('/account/addresses', 'PUT', { addresses: [] }, cookie)).status, 200);
  assert.equal((await call('/auth/logout', 'POST', {})).status, 200);
});
test('catalog, contact and newsletter save real data and reject invalid requests', async () => {
  assert.equal((await call('/health')).status, 200);
  assert.equal((await call('/products')).data.products.length, 20);
  assert.equal((await call('/products/missing')).status, 404);
  assert.equal((await call('/newsletter', 'POST', { email: { $ne: null } })).status, 400);
  for (let i = 0; i < 2; i++) assert.equal((await call('/newsletter', 'POST', { email: 'NEWS@example.com' })).status, 200);
  assert.equal(await Subscriber.countDocuments(), 1);
  assert.equal((await call('/contact', 'POST', { name: 'Test', email: 'test@example.com', subject: 'Order Support', message: 'Please help with my order.' })).status, 201);
  assert.equal(await Contact.countDocuments(), 1);
  const denied = await fetch(base + '/contact', { method: 'POST', headers: { Origin: 'https://untrusted.example', 'Content-Type': 'application/json' }, body: '{}' });
  assert.equal(denied.status, 403);
  assert.equal((await call('/unknown')).status, 404);
});
